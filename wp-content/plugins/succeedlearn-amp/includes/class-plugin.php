/**
 * Main Plugin Class
 */
class Plugin {

	/**
	 * @var Plugin|null
	 */
	private static $instance = null;

	/**
	 * @var Template_Manager
	 */
	private $template_manager;

	/**
	 * @var Config
	 */
	private $config;

	/**
	 * @var Admin
	 */
