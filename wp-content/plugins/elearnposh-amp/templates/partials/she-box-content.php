<p class="pa-p">Therefore, as a general compliance approach, organisations covered by the POSH Act should register themselves and keep their Internal Committee and nodal officer details updated on the relevant portal, the central SHe-Box portal, or where applicable, a State-specific portal.</p>

<h3 class="pa-h3" id="shebox-employer-role">What is the role of employers in SHe-Box?</h3>
<p class="pa-p">Employers have responsibilities both under the POSH Act and in relation to SHe-Box.</p>
<p class="pa-lead">Employers should:</p>
<ul class="pa-list">
	<li>constitute an Internal Committee wherever required</li>
	<li>ensure the IC is properly composed under the POSH Act</li>
	<li>display information about the complaint mechanism</li>
	<li>conduct POSH awareness and training programmes</li>
	<li>assist in timely handling of complaints</li>
	<li>register the organisation and IC details on SHe-Box</li>
	<li>keep organisation, workplace, and nodal officer details updated</li>
	<li>cooperate with authorities when a complaint is routed through the portal</li>
</ul>
<p class="pa-p">This is important because accurate organisation and IC details help complaints reach the correct authority quickly.</p>
