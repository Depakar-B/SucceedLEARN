<h3 class="pa-h3" id="shebox-who-can-use">Who can use SHe-Box?</h3>
<p class="pa-p">SHe-Box can be used by any woman who has faced sexual harassment connected to a workplace or work-related setting.</p>
<p class="pa-p">It is not limited to permanent employees. It can be used by women working in different roles and sectors, including:</p>
<ul class="pa-list">
	<li>employees</li>
	<li>interns</li>
	<li>trainees</li>
	<li>consultants</li>
	<li>contractual workers</li>
	<li>visitors</li>
	<li>domestic workers</li>
	<li>women in organised and unorganised sectors</li>
	<li>women working in government offices, private companies, institutions, and informal workplaces</li>
</ul>
<p class="pa-p">The incident may take place inside an office, during a work meeting, at a work event, during official travel, at a client location, in a household where domestic work is performed, or through work-related digital communication.</p>

<h3 class="pa-h3" id="shebox-complaint-types">What complaints can be filed?</h3>
<p class="pa-p">SHe-Box is specifically for complaints of sexual harassment at the workplace.</p>
<p class="pa-p">Sexual harassment may include:</p>
<ul class="pa-list">
	<li>unwelcome physical contact or advances</li>
	<li>demand or request for sexual favours</li>
	<li>sexually coloured remarks</li>
	<li>showing pornography</li>
	<li>unwelcome sexual messages or images</li>
	<li>repeated sexual jokes or comments</li>
	<li>inappropriate comments about someone’s body</li>
	<li>pressure for personal meetings</li>
	<li>sexual suggestions linked to work benefits or threats</li>
	<li>any unwelcome conduct of a sexual nature that creates a hostile, intimidating, humiliating, or uncomfortable work environment</li>
</ul>
<p class="pa-p">The key point is that the conduct must be unwelcome and connected to the workplace.</p>

<h2 class="pa-h2" id="shebox-filing-complaint">Filing a POSH Complaint on SHe-Box</h2>

<h3 class="pa-h3" id="shebox-complaint-process">How does the POSH complaint process work?</h3>
<p class="pa-p">The complaint process begins when the aggrieved woman, or someone authorised to act on her behalf, submits a POSH complaint on the SHe-Box portal.</p>
<p class="pa-p">After submission, the complaint is forwarded to the appropriate authority. If the workplace has an Internal Committee, the complaint is routed to that committee. If the matter falls under the jurisdiction of a Local Committee, it is routed there.</p>
<p class="pa-p">The Ministry has described the portal as enabling online complaint filing, automatic forwarding to the concerned Internal Committee or Local Committee, and real-time tracking.</p>

<h3 class="pa-h3" id="shebox-file-on-behalf">Can someone file a complaint on behalf of the woman?</h3>
<p class="pa-p">Yes. A complaint may be filed by the aggrieved woman herself or by another person on her behalf.</p>
<p class="pa-p">This can help where the woman needs assistance, is unable to file the complaint herself, or wants support from someone she trusts. When another person files the complaint, the portal may ask for details of that person, their relationship with the complainant, and confirmation that the complaint is being filed with the complainant’s knowledge or authority.</p>

<h3 class="pa-h3" id="shebox-complaint-details">What details may be needed while filing a complaint?</h3>
<p class="pa-p">The portal may ask for details such as:</p>
<ul class="pa-list">
	<li>complainant’s name and contact details</li>
	<li>work status</li>
	<li>workplace or organisation details</li>
	<li>details of the respondent</li>
	<li>date, place, and description of the incident</li>
	<li>nature of harassment</li>
	<li>supporting material, if available</li>
	<li>witness details, if any</li>
</ul>
<p class="pa-p">It is useful to keep relevant material ready, such as emails, messages, screenshots, recordings, documents, or names of witnesses. Even if every detail is not available, the complainant should describe the incident clearly and truthfully.</p>

<h3 class="pa-h3" id="shebox-confidentiality">Is confidentiality maintained?</h3>
<p class="pa-p">Yes. Confidentiality is an important part of the POSH process.</p>
<p class="pa-p">Complaint details are not meant to be publicly visible. They are shared with the authority responsible for handling the matter. This helps protect the identity, dignity, and privacy of the complainant while ensuring that the complaint reaches the correct forum.</p>
<p class="pa-p">The official government communication describes the portal as a secure and confidential platform for workplace sexual harassment complaints.</p>

<h3 class="pa-h3" id="shebox-track-complaint">Can the complaint be tracked?</h3>
<p class="pa-p">Yes. One of the important features of SHe-Box is that the complainant can track the status of her complaint.</p>
<p class="pa-p">This means the complainant can see whether the complaint has been submitted, forwarded, or is pending with the concerned authority. This improves transparency and reduces the risk of complaints remaining unnoticed or unattended.</p>

<h3 class="pa-h3" id="shebox-after-committee">What happens after the complaint reaches the committee?</h3>
<p class="pa-p">Once the complaint reaches the relevant Internal Committee or Local Committee, the committee is expected to handle it according to the POSH Act process.</p>
<p class="pa-p">The committee may:</p>
<ul class="pa-list">
	<li>review the complaint</li>
	<li>contact the complainant</li>
	<li>seek further details</li>
	<li>notify the respondent</li>
	<li>conduct hearings</li>
	<li>examine documents and evidence</li>
	<li>speak to witnesses</li>
	<li>assess the material placed before it</li>
	<li>submit findings and recommendations</li>
</ul>
<p class="pa-p">The process must follow principles of fairness. The complainant must be heard, and the respondent must also get an opportunity to respond.</p>

