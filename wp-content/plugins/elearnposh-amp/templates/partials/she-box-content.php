<h2 class="pa-h2" id="shebox-introduction">SHe-Box Introduction</h2>

<h3 class="pa-h3" id="shebox-what-is">What is SHe-Box?</h3>
<p class="pa-p">SHe-Box stands for Sexual Harassment electronic Box. It is an online complaint management portal created by the Government of India for complaints relating to sexual harassment of women at the workplace.</p>
<p class="pa-p">The portal is managed by the Ministry of Women and Child Development and is connected to the implementation of the Sexual Harassment of Women at Workplace (Prevention, Prohibition and Redressal) Act, 2013, commonly known as the POSH Act.</p>
<p class="pa-p">In simple terms, SHe-Box gives women an official online platform to file workplace sexual harassment complaints. Once a complaint is submitted, it is forwarded to the authority that has jurisdiction to act on it. The official portal describes SHe-Box as a single-window platform available to every woman, whether she works in the organised or unorganised sector, and whether her workplace is public or private.</p>
