<h3 class="pa-h3" id="shebox-registration-details">What details should an organisation keep ready before registration on SHe-Box portal?</h3>
<p class="pa-p">Before registering on SHe-Box, an organisation should keep the following information ready:</p>
<ul class="pa-list">
	<li>legal name of the organisation</li>
	<li>head office address</li>
	<li>workplace or branch details, if applicable</li>
	<li>state and district details</li>
	<li>official email ID and phone number</li>
	<li>name and designation of the head of office or authorised signatory</li>
	<li>details of the Internal Committee</li>
	<li>name and contact details of the Presiding Officer</li>
	<li>names and details of IC members</li>
	<li>name, designation, mobile number, and email ID of the SHe-Box nodal officer</li>
	<li>number of employees, if requested</li>
	<li>date of constitution of the Internal Committee, if requested</li>
</ul>
<p class="pa-p">The organisation may be required to upload relevant/supporting documents on the SHe-Box portal, such as company registration details, GST details, PAN details, address proof, or any authorisation/official document required by the portal or the concerned District/State authority for verification.</p>
<p class="pa-p">Organisations should ensure that the details entered are accurate and kept updated.</p>

<h3 class="pa-h3" id="shebox-nodal-officer">Who is a nodal officer for SHe-Box?</h3>
<p class="pa-p">The official private head office user manual describes the nodal officer as the authorised person responsible for ensuring compliance with the POSH Act and monitoring the SHe-Box portal.</p>
<p class="pa-p">For an organisation, the nodal officer may be someone such as an HR manager, compliance officer, legal officer, senior administrator, or another authorised person who can monitor complaints and coordinate with the Internal Committee or relevant authorities.</p>

<h3 class="pa-h3" id="shebox-nodal-responsibilities">What are the responsibilities of the organisation’s nodal officer according to SHe-Box or MWCD Guidelines?</h3>
<p class="pa-p">The organisation’s nodal officer should:</p>
<ul class="pa-list">
	<li>monitor the SHe-Box portal regularly</li>
	<li>ensure organisation and IC details are correctly registered</li>
	<li>update details when there is any change in IC composition, office address, or contact information</li>
	<li>coordinate with the Internal Committee when a complaint is received</li>
	<li>ensure that complaints are not ignored or delayed</li>
	<li>help maintain confidentiality</li>
	<li>assist with compliance documentation</li>
	<li>coordinate with district or government authorities, if required</li>
	<li>ensure timely response to portal communications</li>
	<li>support awareness about SHe-Box within the organisation</li>
</ul>
<p class="pa-p">The nodal officer should not replace the Internal Committee. The IC remains responsible for conducting the POSH inquiry. The nodal officer’s role is mainly coordination, monitoring, compliance, and communication.</p>

<h3 class="pa-h3" id="shebox-mandatory-registration">Is SHe-Box registration mandatory for organisations?</h3>
<p class="pa-p">Under the POSH Act, every employer with 10 or more employees is required to constitute an Internal Committee. The SHe-Box portal supports this compliance framework by maintaining details of Internal Committees, Local Committees, nodal officers, and complaint routing.</p>
<p class="pa-p">At the central level, SHe-Box is designed to function as a national repository of Internal Committees and Local Committees across government and private sector workplaces. Therefore, organisations covered by the POSH Act are generally advised to register their workplace, Internal Committee, and nodal officer details on the SHe-Box portal.</p>
<p class="pa-p">Some States and Union Territories have also issued specific directions or created State-level mechanisms requiring organisations to register their IC details. Based on publicly available information, the following jurisdictions have issued clear directions or have a specific registration mechanism:</p>
